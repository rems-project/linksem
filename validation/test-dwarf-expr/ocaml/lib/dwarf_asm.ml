(* Claude: the assembler source of a test program: _start sets the registers, stops at
   dw_here, exits; dw_mem is a known 256-byte block; DWARF 4 .debug_info/.debug_abbrev
   describe a subprogram "main" (frame base DW_OP_call_frame_cfa) whose variables are
   the expressions under test, each with a DW_AT_location exprloc; .debug_frame comes
   from the .cfi directives. *)

let emit (arch : Arch.t) (vars : (string * string list) list) : string =
  let b = Buffer.create 65536 in
  let p fmt = Printf.bprintf b fmt in
  p "# Claude: generated by dwexpr_build for %s; do not edit\n" arch.name;
  p "\t.cfi_sections .debug_frame\n\t.text\n\t.globl _start\n\t.type _start, %s\n_start:\n\t.cfi_startproc\n" arch.fn_type;
  Buffer.add_string b arch.prologue;
  (* the frame pointer last, so that the Mem loads (which may use it on no architecture, but still) are done *)
  List.iter (fun (r, v) -> if r <> arch.cfa_reg then Buffer.add_string b (arch.set_reg r v)) arch.regs;
  List.iter (fun (r, v) -> if r = arch.cfa_reg then Buffer.add_string b (arch.set_reg r v)) arch.regs;
  p "\t.globl dw_here\ndw_here:\n\tnop\n";
  Buffer.add_string b arch.exit_seq;
  p "\t.cfi_endproc\n.Lend_start:\n\t.size _start, .Lend_start-_start\n";
  p "\n\t.data\n\t.globl dw_mem\n\t.p2align 4\ndw_mem:\n";
  for i = 0 to Arch.mem_size / 16 - 1 do
    p "\t.byte %s\n" (String.concat "," (List.init 16 (fun j -> Printf.sprintf "0x%02x" (Arch.mem_byte (16 * i + j)))))
  done;
  p "\t.size dw_mem, %d\n" Arch.mem_size;
  (* abbreviations *)
  p "\n\t.section .debug_abbrev,\"\",%s\n.Labbrev:\n" arch.progbits;
  p "\t.uleb128 1\n\t.uleb128 0x11\n\t.byte 1\n";                       (* DW_TAG_compile_unit, has children *)
  p "\t.uleb128 0x25\n\t.uleb128 0x08\n";                               (* DW_AT_producer string *)
  p "\t.uleb128 0x13\n\t.uleb128 0x0b\n";                               (* DW_AT_language data1 *)
  p "\t.uleb128 0x03\n\t.uleb128 0x08\n";                               (* DW_AT_name string *)
  p "\t.uleb128 0x11\n\t.uleb128 0x01\n";                               (* DW_AT_low_pc addr *)
  p "\t.uleb128 0x12\n\t.uleb128 0x07\n";                               (* DW_AT_high_pc data8 (length) *)
  p "\t.byte 0,0\n";
  p "\t.uleb128 2\n\t.uleb128 0x24\n\t.byte 0\n";                       (* DW_TAG_base_type *)
  p "\t.uleb128 0x03\n\t.uleb128 0x08\n";                               (* name *)
  p "\t.uleb128 0x3e\n\t.uleb128 0x0b\n";                               (* DW_AT_encoding data1 *)
  p "\t.uleb128 0x0b\n\t.uleb128 0x0b\n";                               (* DW_AT_byte_size data1 *)
  p "\t.byte 0,0\n";
  p "\t.uleb128 3\n\t.uleb128 0x2e\n\t.byte 1\n";                       (* DW_TAG_subprogram, has children *)
  p "\t.uleb128 0x03\n\t.uleb128 0x08\n";                               (* name *)
  p "\t.uleb128 0x3f\n\t.uleb128 0x19\n";                               (* DW_AT_external flag_present *)
  p "\t.uleb128 0x11\n\t.uleb128 0x01\n";                               (* low_pc *)
  p "\t.uleb128 0x12\n\t.uleb128 0x07\n";                               (* high_pc data8 *)
  p "\t.uleb128 0x40\n\t.uleb128 0x18\n";                               (* DW_AT_frame_base exprloc *)
  p "\t.byte 0,0\n";
  p "\t.uleb128 4\n\t.uleb128 0x34\n\t.byte 0\n";                       (* DW_TAG_variable *)
  p "\t.uleb128 0x03\n\t.uleb128 0x08\n";                               (* name *)
  p "\t.uleb128 0x49\n\t.uleb128 0x13\n";                               (* DW_AT_type ref4 *)
  p "\t.uleb128 0x02\n\t.uleb128 0x18\n";                               (* DW_AT_location exprloc *)
  p "\t.byte 0,0\n";
  p "\t.byte 0\n";
  (* the compilation unit *)
  p "\n\t.section .debug_info,\"\",%s\n.Lcu_start:\n" arch.progbits;
  p "\t.4byte .Lcu_end-.Lcu_start-4\n\t.2byte 4\n\t.4byte .Labbrev\n\t.byte 8\n";
  p "\t.uleb128 1\n\t.asciz \"dwexpr (Claude scratch harness)\"\n\t.byte 0x0c\n\t.asciz \"dwexpr.c\"\n\t.8byte _start\n\t.8byte .Lend_start-_start\n";
  p ".Ltype_ulong:\n\t.uleb128 2\n\t.asciz \"unsigned long\"\n\t.byte 0x07\n\t.byte 8\n";
  p "\t.uleb128 3\n\t.asciz \"main\"\n\t.8byte _start\n\t.8byte .Lend_start-_start\n\t.uleb128 .Lfb_end-.Lfb_start\n.Lfb_start:\n\t.byte 0x9c\n.Lfb_end:\n";
  List.iter (fun (v, directives) ->
      p "\t.uleb128 4\n\t.asciz \"%s\"\n\t.4byte .Ltype_ulong-.Lcu_start\n\t.uleb128 .L%s_end-.L%s_start\n.L%s_start:\n" v v v v;
      List.iter (fun d -> p "%s\n" d) directives;
      p ".L%s_end:\n" v) vars;
  p "\t.byte 0\n\t.byte 0\n.Lcu_end:\n";
  Buffer.contents b
